// ============================================================================
// src/platform/sdl/input_sdl.cpp -- Platform::Input over SDL3
// ============================================================================
// Phase D.4 SDL steps I2 (the keyboard) onward (plan §A.4, §E).
//
// RETAIL (Input::Device, Runtime-x64.dll):
//   Update 0x1800e1490: zero the scratch; PlatformGetKeyboardState; UpdateState; the same
//       for the mouse; PlatformUpdate. MainLoop::Frame calls it BEFORE the message pump.
//   PlatformGetKeyboardState 0x1800e1c60:
//       DirectInput path: keyboard->GetDeviceState(0x100, keys) (+0x48); on failure
//           Acquire while DIERR_INPUTLOST and return with the scratch untouched (zero:
//           every key released); else out[kScanCodeToIndex[i]] = keys[i] & 0x80, i 0..255.
//       legacy path: if GetForegroundWindow() == hwnd, out[i] = GetAsyncKeyState(
//           kIndexToVirtualKey[i]) & 0x8000, i 0..0x68; else all zero.
//
// WHAT SDL DOES DIFFERENTLY, AND WHY IT IS ACCEPTED
//  * Freshness. DirectInput's GetDeviceState and GetAsyncKeyState are LIVE when the
//    poller runs. SDL_GetKeyboardState is only as fresh as the last SDL_PumpEvents, and
//    the frame pumps AFTER the poll (mainloop_frame.cpp: poll, reap, pump, update). So
//    Device::Update calls Platform::Input::Poll() first, which pumps (plan §E rule 1).
//    Without it every key would land one tick late. It queues events; they are still
//    DISPATCHED at the frame's pump, in order. As with live polling, a key pressed and
//    released between two polls is never seen.
//  * ReadKeyboard builds the 256 DIK bytes DirectInput returned, from SDL's per-scan-code
//    state through kSdlScancodeToDik (src/platform/common/sdl_dik_tables.h, generated by
//    tools/sdl_dik/gen_sdl_dik_tables.py). Both are physical positions, layout-
//    independent. The retail unpack loop then runs unchanged on the buffer, so the
//    index-104 alias is kept byte for byte: a scan code SDL knows and DirectInput does not
//    goes to DIK 0, which retail's table aliases to index 104, and the loop's last write
//    to index 104 (DIK 0xFF, no key) wins, as it does for every unmapped DirectInput code.
//  * Focus. DirectInput's keyboard is DISCL_FOREGROUND: GetDeviceState fails unless the
//    window is the foreground window. SDL gives the window keyboard focus exactly when it
//    is the foreground window (WIN_UpdateFocus: GetForegroundWindow() == hwnd). Without
//    it ReadKeyboard reports DIERR_NOTACQUIRED and leaves the buffer alone, so the
//    poller's failure exit runs: the re-acquire attempt, then all keys released.
//  * The legacy path. IsForeground is SDL's keyboard-focus test (the same rule). The
//    per-key state comes from SDL's scan-code state through kVirtualKeyToSdlScancode: a
//    generic modifier VK (SHIFT / CONTROL / MENU) is down when either side is.
//    GetAsyncKeyState follows the active layout's VK assignment; the table is the US
//    layout's positions (on another layout a letter / OEM key reads the key at the US
//    position), the keypad digits read regardless of NumLock (GetAsyncKeyState's
//    VK_NUMPADn are NumLock-on only), and VK_OEM_8 (index 104) has no key. The legacy
//    path is off by default (Input/Legacy = 0).
//  * No text input. Retail types from key indices and SelectCharacter's US table
//    (editelement.cpp); SDL_StartTextInput is never called. Key repeat stays
//    UpdateState's own 0.3 s / 0.25 s timer; SDL's repeat flag is never read.
// ============================================================================

#include "platform_input.h"
#include "sdl_dik_tables.h"
#include "window_sdl_internal.h"

#include <SDL3/SDL_events.h>
#include <SDL3/SDL_keyboard.h>

#include <cstring>

namespace Platform {
namespace Input {

namespace {

// True when the game window has SDL's keyboard focus (the window is the foreground
// window, as DISCL_FOREGROUND / GetForegroundWindow require).
bool GameWindowHasKeyboardFocus() {
    return SDL_GetKeyboardFocus() == Window::Sdl::GameWindow();
}

}  // namespace

void Poll() {
    SDL_PumpEvents();
}

int32_t ReadKeyboard(void* /*device*/, uint8_t dik[256]) {
    if (!GameWindowHasKeyboardFocus()) return kNotAcquired;

    int count = 0;
    const bool* state = SDL_GetKeyboardState(&count);
    if (count > kSdlScancodeCount) count = kSdlScancodeCount;

    std::memset(dik, 0, 256);
    for (int s = 0; s < count; ++s) {
        if (state[s]) dik[kSdlScancodeToDik[s]] = 0x80;
    }
    return kOk;
}

bool IsForeground(void* /*window*/) {
    // `window` is the game window's native handle, the only window there is.
    return GameWindowHasKeyboardFocus();
}

int16_t AsyncKeyState(int32_t vk) {
    int count = 0;
    const bool* state = SDL_GetKeyboardState(&count);
    for (const uint16_t s : kVirtualKeyToSdlScancode[static_cast<uint8_t>(vk)]) {
        if (s != 0 && s < count && state[s]) return INT16_MIN;   // bit 15: down now
    }
    return 0;
}

}  // namespace Input
}  // namespace Platform
