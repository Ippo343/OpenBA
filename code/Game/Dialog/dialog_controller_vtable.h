#pragma once
// code/Game/Dialog/dialog_controller_vtable.h — Wave 10D lane VTFID
//
// Make our standalone UI::DialogController subclass vtables hold, in the slots
// the subclass does not override, THE INHERITED BASE ENTRY — which is what
// retail's derived tables hold and what C++ requires.
//
// ---------------------------------------------------------------------------
// THE INFIDELITY THIS FIXES
// ---------------------------------------------------------------------------
// Every standalone subclass table in code/Game/ is built by one idiom:
//
//     for (int i = 0; i < kSlots; ++i) g_vt[i] = &StubNop;   // file-local no-op
//     g_vt[0] = &Dtor;  g_vt[2] = &GetTypeId;  g_vt[4] = ...;
//
// A derived vtable does not omit the virtuals it does not override — it COPIES
// THE BASE ENTRY. Measured out of Application-x64.exe by
// tools/dlgctrl_vtable_audit.py: across the 38 subclasses that have a
// standalone table, retail inherits 166 slots where we hold a file-local stub.
// So the ported `??_7DialogController@UI@@6B@` bodies were unreachable for a
// reason that is OURS, not a property of the DLL.
//
// Seven of the eight inherited base bodies are literally `RET 0`, so the
// substitution changed no observable behaviour — only WHOSE no-op ran, and
// therefore whether the port was exercised at all. That is exactly why it
// survived: it is invisible until you go and read retail's tables.
//
// ---------------------------------------------------------------------------
// WHAT IS FILLED, AND WHAT IS DELIBERATELY NOT
// ---------------------------------------------------------------------------
// A slot is filled only when BOTH hold:
//
//   1. RETAIL INHERITS IT. Per class, read out of the exe: an inherited slot
//      holds a 6-byte `FF 25 rel32` thunk whose import-table entry names the
//      base virtual outright, so this is a reading and not a rule applied 38
//      times. The per-class mask lives in dialog_controller_vtable.cpp and is
//      regenerated by `python tools/dlgctrl_vtable_audit.py --gen`.
//
//   2. THE SLOT STILL HOLDS THAT FILE'S OWN STUB. Each site passes its
//      `StubNop`, and Apply() only overwrites slots still equal to it. So a
//      slot the file DELIBERATELY overrides is never clobbered — which matters:
//      ten slots (nine of them slot 8 `OnUpdate`, plus StatusBarUI's slot 4)
//      are standalone-only overrides that drive live panel refresh where retail
//      inherits. Overwriting those would break working panels to feed a
//      counter. The stub identity is the guard, not a comment asking future
//      edits to be careful.
//
// Slots 0/1/2 are never filled: retail OVERRIDES them in every subclass (37 of
// 38 for slot 1, all 38 for slots 0 and 2), so there is no inherited entry to
// copy. Where our table stubs slot 1 (`TypeName`) that remains an infidelity,
// but it is a MISSING EXE OVERRIDE, not a missing inherited slot — a different
// debt, recorded in docs/runtime_port/WAVE10D_LANE_VTFID.md rather than papered
// over here.
//
// ---------------------------------------------------------------------------
// WHY REGISTER-THEN-APPLY, RATHER THAN FILLING AT STATIC INIT
// ---------------------------------------------------------------------------
// The tables are built by static initialisers, which run BEFORE main — and
// before ResolveInit() has run and before
// RuntimePortInit() has registered the ported bodies. Resolving there would
// hand back null and fill the tables with nulls. So Register() only RECORDS the
// table at static-init time, and Apply() does the resolution and the fill from
// one call in the standalone boot sequence, after the port registry is live.
// Patching the table (rather than the objects) means objects constructed either
// side of Apply() see the same array.
#include <cstddef>

namespace UIDialogControllerVtable {

// Record a standalone subclass vtable to be filled by Apply().
// `cls` must be the registered type name (e.g. "DestroyUI"); an unknown name is
// reported by Apply() rather than silently ignored.
void Register(void** vt, int nslots, const char* cls, void* stub);

// Resolve the inherited base bodies and fill every registered table.
// Call ONCE, after RuntimePortInit() and AddressRegistryInit().
// Returns the number of slots filled.
int Apply();

// Registered/filled counts for the report line. Valid after Apply().
struct Stats {
    int tables;         // tables registered
    int unknown;        // registered under a name with no retail mask
    int filled;         // slots filled with an inherited base body
    int keptOverride;   // retail inherits, but the file overrides — left alone
    int unresolved;     // retail inherits, but the base body would not resolve
};
Stats GetStats();

}  // namespace UIDialogControllerVtable

// Register one standalone subclass vtable. Place it inside the class's
// namespace, anywhere after the table's own initialiser — Register() only
// RECORDS, so the order relative to the file's own slot wiring does not matter;
// Apply() reads the table long after every static initialiser has run.
//
//     DLGCTRL_VTABLE_INHERIT(g_vt, kSlots, "DestroyUI", &StubNop);
#define DLGCTRL_VTABLE_INHERIT(vt, nslots, cls, stub)                          \
    static struct DlgCtrlVtReg_ {                                              \
        DlgCtrlVtReg_() {                                                      \
            ::UIDialogControllerVtable::Register(                              \
                (vt), (nslots), (cls), reinterpret_cast<void*>(stub));         \
        }                                                                      \
    } g_dlgCtrlVtReg_
