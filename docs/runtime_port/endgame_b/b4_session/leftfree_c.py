#!/usr/bin/env python
"""Section C of LEFT_FREE.md: every counted cast outside src/render/dx11/, grouped by the words of its tag.

usage (repo root):  python docs/runtime_port/endgame_b/b4_session/leftfree_c.py [--check]
Prints the markdown of section C. With --check it prints only the group counts and exits 1 when
the WORK group is not empty (the B.4 closing form of acceptance line 01: every unmarked cast
outside src/render/dx11/ is DEFERRED to a named later task, or ruled to stay listed).
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import castmetric as CM

DIRS = ['code', 'runtime', 'standalone']
G_DX = 'DEFERRED: dx11 seam step'
G_RD = 'DEFERRED: retail-difference task (known_port_issues 13-14)'
G_NP = 'DEFERRED: named prerequisite'
G_RU = 'RULED: stays listed (FLOOR section 4 bars a marker on a this / self operand)'
G_WK = 'WORK (blocker on the line)'
ORDER = [G_RD, G_NP, G_DX, G_RU, G_WK]


def group(tag):
    t = tag
    if re.search(r'dx11 seam', t):
        return G_DX
    if re.search(r'S4 ruling: no marker', t):
        return G_RU
    if re.search(r'DEFERRED \(named prerequisite|audit DEFERRED \((H5|ctor|zeroing|Work leaves)|audit DEFERRED:RtIo', t):
        return G_NP
    if re.search(r'retail-difference|known_port_issues|\brow \d+|retail DIFFERENCE|wrong object|vptr guard|'
                 r'vptr test|vtable-null guard|null-vptr guard|null-allocator arm|retail calls Time::AsSeconds|'
                 r'SIG Pf_EntityResolvePos|pointer bits read as ticks|integer time', t):
        return G_RD
    return G_WK


def collect():
    """{group: [(rel, line, tag)]} for every counted cast outside src/render/dx11/."""
    rows = CM.run(DIRS, want_detail=True)
    out = {g: [] for g in ORDER}
    for rel, c, sc, hits in sorted(rows, key=lambda r: r[0]):
        src = CM._CACHE[rel][0].split('\n')
        for h in hits:
            loc, col = h.split('\t')[:2]
            if col.startswith(('tier_i', 'cast_ok')):
                continue
            ln = int(loc.rsplit(':', 2)[1])
            text = src[ln - 1]
            m = re.search(r'//\s*LEFT:\s*(.*)$', text)
            tag = m.group(1).strip() if m else '(no LEFT tag) ' + text.strip()[:120]
            if not m:   # a continuation line: the tag may sit on a neighbouring line of the statement
                for d in (1, -1, 2, -2, 3):
                    j = ln - 1 - d
                    m2 = re.search(r'//\s*LEFT:\s*(.*)$', src[j]) if 0 <= j < len(src) else None
                    if m2:
                        tag = 'as line %d: %s' % (j + 1, m2.group(1).strip())
                        break
            out[group(tag)].append((rel, ln, tag))
    return out


def main():
    out = collect()
    total = sum(len(v) for v in out.values())
    if '--check' in sys.argv:
        for g in ORDER:
            print('%4d  %s' % (len(out[g]), g))
        print('%4d  total' % total)
        return 1 if out[G_WK] else 0
    head = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
    print('## C. Casts left, by reason\n')
    print('Generated by `leftfree_c.py` (this directory) at main `%s`. Grouping is by the words of the tag on each line.\n' % head)
    print('%d counted casts outside `src/render/dx11/` (one row per cast; a line with two casts appears twice).\n' % total)
    print('| group | casts |\n|---|---:|')
    for g in ORDER:
        print('| %s | %d |' % (g, len(out[g])))
    for g in ORDER:
        if not out[g]:
            continue
        print('\n### %s (%d)\n' % (g, len(out[g])))
        print('| file:line | reason on the line |\n|---|---|')
        for rel, ln, tag in out[g]:
            print('| `%s:%d` | %s |' % (rel, ln, tag.replace('|', '/')[:260]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
