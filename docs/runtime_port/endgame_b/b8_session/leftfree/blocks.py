"""Assign every inventory row a target class and a block; write b8_session/INVENTORY.md."""
import re, os, collections
ROOT = r'C:/code/GIT/untitled_rev_eng_project'
S = os.path.dirname(os.path.abspath(__file__))
os.chdir(ROOT)
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(S, 'inventory.tsv'), encoding='utf-8')]
hdr, rows = rows[0], rows[1:]
# LEFT_FREE's raw rows by name (class column, reason column)
lf = {}
for l in open('docs/runtime_port/endgame_b/b4_session/LEFT_FREE.md', encoding='utf-8'):
    m = re.match(r'^\| `([A-Za-z_]\w*)` \| ([^|]*) \| ([^|]*) \| (.*) \|\s*$', l)
    if m:
        lf.setdefault(m.group(1), (m.group(2).strip(), m.group(3).strip(), m.group(4).strip()))
TEMPLATE_RT = ('ExternalPtr', 'Collection::Array', 'Collection::Set', 'InternalPtr', 'Object::InternalPtr',
               'Object::ExternalPtr', 'Array', 'Set')
out = []
for r in rows:
    name, rel, line, addr, gname, first, cls, chdr, cn, lcls, lreason, callers = r
    lfc = lf.get(name, ('', '', ''))
    lfclass, lfreason = lfc[1], lfc[2]
    kind = ''
    target = ''
    m = re.match(r'member of (.+?), not moved', lfclass)
    if m:
        kind = 'member'
        target = m.group(1)
    elif lfclass.startswith('free in retail'):
        kind = 'free'
    elif lfclass.startswith('erased core'):
        kind = 'erased'
    elif lfclass.startswith('forwarder'):
        kind = 'forwarder'
    elif lfclass.startswith('harness'):
        kind = 'harness'
    elif lfclass.startswith('unclear') or lfclass == '':
        kind = 'unclear' if lfclass else 'new (B7)'
    if not target and cls:
        target = cls
    tbase = target.split('<')[0].split('::')[-1]
    # block by the target class's header directory
    if any(target.startswith(t) for t in TEMPLATE_RT) or (chdr.startswith('runtime/') and kind != 'free')             or (kind == 'erased' and re.match(r'Reimpl_Array_Resize_|QwordArraySetSize', name)):
        block = 'RT'
    elif kind in ('free', 'harness') or not target:
        block = 'MISC'
    else:
        d = chdr.rsplit('/', 1)[0] if chdr else ''
        if d == 'code/Game/Component':
            block = 'COMP-A' if tbase in ('CitizenComponent', 'Component', 'CharacterComponent', 'CharacterGrid', 'CharacterDescription', 'ComponentDescription', 'CropFieldComponent', 'CropSlotArray', 'ConsumeProduceComponent', 'ClearAreaComponent', 'AmbientEmitterComponent', 'AmbientEnvironmentComponent', 'AutoPickupComponent') else 'COMP-B'
        elif d == 'code/Game/Game':
            block = 'GAME'
        elif d in ('code/Game/Entity', 'code/Game/Dialog', 'code/Game/Tutorial'):
            block = 'ENT'
        elif d in ('code/Game/Player', 'code/Game/Action', 'code/Game/Work', 'code/Game/Object'):
            block = 'MISC'
        elif d.startswith('runtime/'):
            block = 'RT'
        else:
            block = 'MISC'
    out.append(r + [kind, target, block, lfreason])
cnt = collections.Counter(o[-2] for o in out)
kinds = collections.Counter((o[-2], o[-4]) for o in out)
print(cnt)
with open(os.path.join(S, 'inventory_blocks.tsv'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\t'.join(hdr + ['kind', 'target_class', 'block', 'leftfree_note']) + '\n')
    for o in out:
        f.write('\t'.join(o) + '\n')
# INVENTORY.md
md = []
md.append('# B8 inventory: the free functions of `exe_bodies.h` / `*_funcs.h` (generated by `leftfree_a.py` at the kit commit)\n')
md.append('One row per declaration acceptance.sh line 08 counts (412 at the kit). Columns: the declared name and where; the retail address on the declaration line (or the comment above it); Ghidra\'s name at that address (the exe is stripped: a `FUN_` / ad-hoc name, never a retail symbol -- the CLASS is read from the body: the first parameter is `this` when retail reads it in RCX as the object); the first parameter as declared; the TARGET class (LEFT_FREE.md\'s `member of X` column where it has one, else the first parameter\'s class); the kind from LEFT_FREE.md\'s reason column (`member` = becomes that class\'s member; `forwarder` = its callers call the target, the forwarder is deleted; `erased` = a type-erased core that becomes the class template\'s member (`Array<T>::Resize`, `Set<T>::Insert`, `ExternalPtr<T>::Serialize`); `free` = free in retail, STAYS and stays listed; `harness` = port-only, STAYS; `unclear` / `new (B7)` = the block reads retail and decides); the caller count outside the declaring header (definitions included: read the list); the block that owns it.\n')
md.append('Blocks (B8_RULES.md §3): COMP-A, COMP-B (Component classes), GAME (Game classes), ENT (Entity / Dialog / Tutorial classes), RT (runtime/types classes and the template families), MISC (Player / Action / Work / Object classes, the `free` / `harness` rulings and the `void*`-first retypes), RES (the residue rows, no inventory rows).\n')
md.append('| block | rows | member | forwarder | erased | free | harness | other |\n|---|---:|---:|---:|---:|---:|---:|---:|')
for b in ('COMP-A', 'COMP-B', 'GAME', 'ENT', 'RT', 'MISC'):
    k = lambda x: kinds.get((b, x), 0)
    other = cnt[b] - k('member') - k('forwarder') - k('erased') - k('free') - k('harness')
    md.append(f'| {b} | {cnt[b]} | {k("member")} | {k("forwarder")} | {k("erased")} | {k("free")} | {k("harness")} | {other} |')
md.append('')
for b in ('COMP-A', 'COMP-B', 'GAME', 'ENT', 'RT', 'MISC'):
    md.append(f'\n## {b} ({cnt[b]})\n')
    md.append('| name | declared in | retail | ghidra name | first param | target class | kind | callers (n: first few) | LEFT_FREE note |\n|---|---|---|---|---|---|---|---|---|')
    for o in sorted((o for o in out if o[-2] == b), key=lambda o: (o[-3], o[1], int(o[2]))):
        name, rel, line, addr, gname, first, cls, chdr, cn, lcls, lreason, callers, kind, target, block, note = o
        cl = ' '.join(callers.split()[:4])
        md.append(f'| `{name}` | `{rel}:{line}` | {addr} | `{gname}` | `{first}` | `{target}` | {kind} | {cn}: {cl} | {note[:140]} |')
open('docs/runtime_port/endgame_b/b8_session/INVENTORY.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(md) + '\n')
print('written', len(out))
