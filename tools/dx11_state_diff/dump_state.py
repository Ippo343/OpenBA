#!/usr/bin/env python3
"""Dump full per-draw D3D11 pipeline state from a RenderDoc capture as JSONL.

Written for the VideoDX11 port's per-draw equality pass. Frame-level counters
(draw count, texture count, ...) already match between our renderer and the
shipped DLL; they prove almost nothing, because the simulation is not
frame-deterministic and those numbers move by themselves. This walks every draw
and records the *entire* pipeline state instead.

The one hard requirement is that a record must be comparable across two
different processes. RenderDoc ResourceIds are allocation-order handles, so
`ResourceId::136` in one capture and `ResourceId::136` in another are unrelated.
Every resource reference is therefore replaced by a **content-derived key**:

  shaders   sha1 of the DXBC bytecode
  textures  the creation desc, plus sha1 of mip 0 for textures the GPU does not
            write (render targets and depth buffers get desc + role only, since
            their contents are the frame being rendered)
  buffers   byte length, plus sha1 of the used range for constant buffers
  states    blend/depth/raster/sampler objects are recorded as their actual
            field values, never as a handle

So two records are equal iff the draw was configured the same way, regardless of
which process produced it or in what order D3D11 objects happened to be created.

Usage:
    python dump_state.py <capture.rdc> -o <out.jsonl> [--limit N]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

_DEFAULT_MODULE = r"C:\code\GIT\untitled_rev_eng_project\tools\renderdoc_mcp\runtime"


def load_renderdoc():
    path = os.environ.get("RENDERDOC_MODULE_PATH", _DEFAULT_MODULE)
    if path and path not in sys.path:
        sys.path.insert(0, path)
    if sys.platform == "win32" and hasattr(os, "add_dll_directory") and os.path.isdir(path):
        os.add_dll_directory(path)
    import renderdoc  # noqa: E402

    return renderdoc


rd = load_renderdoc()


# ── small helpers ────────────────────────────────────────────────────────────

def sha(data) -> str:
    return hashlib.sha1(bytes(data)).hexdigest()[:16]


def enum(v) -> str:
    """Enum -> bare name ('Triangle_List'), so records stay readable in a diff."""
    s = str(v)
    return s.split(".")[-1] if "." in s else s


def fmt_str(f) -> str:
    try:
        return str(f.Name())
    except Exception:
        return str(f)


def g(obj, name, default=None):
    """Field access that tolerates RenderDoc version drift."""
    try:
        return getattr(obj, name)
    except Exception:
        return default


def is_null(rid) -> bool:
    return rid is None or int(rid) == 0


# ── resource identity ────────────────────────────────────────────────────────

class ResourceKeys:
    """Maps ResourceId -> stable content-derived key, cached per capture."""

    def __init__(self, ctrl):
        self.ctrl = ctrl
        self.cache: dict = {}
        self.textures = {int(t.resourceId): t for t in ctrl.GetTextures()}
        self.buffers = {int(b.resourceId): b for b in ctrl.GetBuffers()}
        self.names = {}
        for r in ctrl.GetResources():
            if not r.autogeneratedName:
                self.names[int(r.resourceId)] = str(r.name)
        # Textures the GPU writes: contents are the frame itself, so hashing
        # them would just re-measure the simulation's non-determinism.
        self.gpu_written = set()
        target_flags = 0
        for flag in ("ColorTarget", "DepthTarget"):
            f = g(rd.TextureCategory, flag)
            if f is not None:
                target_flags |= int(f)
        for rid, t in self.textures.items():
            if int(t.creationFlags) & target_flags:
                self.gpu_written.add(rid)

    def texture(self, rid) -> str:
        if is_null(rid):
            return "-"
        key = int(rid)
        if key in self.cache:
            return self.cache[key]
        t = self.textures.get(key)
        if t is None:
            out = self._fallback(key)
        else:
            desc = (f"tex:{enum(t.type)}:{t.width}x{t.height}x{t.depth}"
                    f":m{t.mips}:a{t.arraysize}:{fmt_str(t.format)}"
                    f":ms{t.msSamp}x{t.msQual}")
            if key in self.gpu_written:
                # Identify by role, not contents.
                out = f"{desc}:rendertarget"
            else:
                out = f"{desc}:{self._tex_hash(t)}"
            named = self.names.get(key)
            if named:
                out += f":'{named}'"
        self.cache[key] = out
        return out

    def _tex_hash(self, t) -> str:
        try:
            data = self.ctrl.GetTextureData(t.resourceId, rd.Subresource(0, 0, 0))
            return sha(data)
        except Exception:
            return "nohash"

    def buffer(self, rid) -> str:
        if is_null(rid):
            return "-"
        key = int(rid)
        ck = ("buf", key)
        if ck in self.cache:
            return self.cache[ck]
        b = self.buffers.get(key)
        out = f"buf:{b.length}" if b is not None else self._fallback(key)
        named = self.names.get(key)
        if named:
            out += f":'{named}'"
        self.cache[ck] = out
        return out

    def buffer_hash(self, rid, offset: int, size: int) -> str:
        """Content hash of a constant-buffer range. Not cached: contents change."""
        if is_null(rid) or size <= 0:
            return "-"
        try:
            data = self.ctrl.GetBufferData(rid, offset, size)
            return sha(data)
        except Exception:
            return "nohash"

    def _fallback(self, key: int) -> str:
        named = self.names.get(key)
        return f"unknown:'{named}'" if named else "unknown"


# ── per-draw state extraction ────────────────────────────────────────────────

def shader_key(pipe, stage, cache: dict) -> str:
    """sha1 of the shader's DXBC. Stable across processes; ResourceId is not."""
    try:
        refl = pipe.GetShaderReflection(stage)
    except Exception:
        refl = None
    if refl is None:
        return "-"
    rid = int(g(refl, "resourceId", 0) or 0)
    if rid and rid in cache:
        return cache[rid]
    raw = g(refl, "rawBytes", None)
    if raw is None or len(raw) == 0:
        key = "-"
    else:
        key = f"{enum(g(refl, 'encoding', ''))}:{len(raw)}:{sha(raw)}"
    if rid:
        cache[rid] = key
    return key


def input_layout(ia) -> list:
    out = []
    for e in g(ia, "layouts", []) or []:
        out.append([
            str(g(e, "semanticName", "")),
            int(g(e, "semanticIndex", 0)),
            fmt_str(g(e, "format", None)),
            int(g(e, "inputSlot", 0)),
            int(g(e, "byteOffset", 0)),
            bool(g(e, "perInstance", False)),
            int(g(e, "instanceDataStepRate", 0)),
        ])
    return out


def vertex_buffers(ia, keys) -> list:
    out = []
    for i, vb in enumerate(g(ia, "vertexBuffers", []) or []):
        rid = g(vb, "resourceId", None)
        if is_null(rid):
            continue
        out.append([i, keys.buffer(rid), int(g(vb, "byteStride", 0)), int(g(vb, "byteOffset", 0))])
    return out


def rasterizer_state(rs) -> dict:
    st = g(rs, "state", None)
    if st is None:
        return {}
    return {
        "fill": enum(g(st, "fillMode", "")),
        "cull": enum(g(st, "cullMode", "")),
        "frontCCW": bool(g(st, "frontCCW", False)),
        "depthBias": int(g(st, "depthBias", 0)),
        "depthBiasClamp": round(float(g(st, "depthBiasClamp", 0.0)), 6),
        "slopeScaledDepthBias": round(float(g(st, "slopeScaledDepthBias", 0.0)), 6),
        "depthClip": bool(g(st, "depthClip", False)),
        "scissorEnable": bool(g(st, "scissorEnable", False)),
        "multisampleEnable": bool(g(st, "multisampleEnable", False)),
        "antialiasedLines": bool(g(st, "antialiasedLines", False)),
        "forcedSampleCount": int(g(st, "forcedSampleCount", 0)),
        "conservative": enum(g(st, "conservativeRasterization", "")),
    }


def viewports(rs) -> list:
    out = []
    for v in g(rs, "viewports", []) or []:
        if not g(v, "enabled", True) and g(v, "width", 0) == 0:
            continue
        if float(g(v, "width", 0)) == 0.0 and float(g(v, "height", 0)) == 0.0:
            continue
        out.append([round(float(g(v, "x", 0)), 3), round(float(g(v, "y", 0)), 3),
                    round(float(g(v, "width", 0)), 3), round(float(g(v, "height", 0)), 3),
                    round(float(g(v, "minDepth", 0)), 4), round(float(g(v, "maxDepth", 0)), 4)])
    return out


def scissors(rs) -> list:
    out = []
    for s in g(rs, "scissors", []) or []:
        if not g(s, "enabled", False):
            continue
        out.append([int(g(s, "x", 0)), int(g(s, "y", 0)),
                    int(g(s, "width", 0)), int(g(s, "height", 0))])
    return out


def blend_state(om) -> dict:
    bs = g(om, "blendState", None)
    if bs is None:
        return {}
    blends = []
    for i, b in enumerate(g(bs, "blends", []) or []):
        if not g(b, "enabled", False) and int(g(b, "writeMask", 0)) == 0xF and i > 0:
            continue
        cb = g(b, "colorBlend", None)
        ab = g(b, "alphaBlend", None)
        blends.append([
            i, bool(g(b, "enabled", False)), bool(g(b, "logicOperationEnabled", False)),
            enum(g(cb, "source", "")), enum(g(cb, "destination", "")), enum(g(cb, "operation", "")),
            enum(g(ab, "source", "")), enum(g(ab, "destination", "")), enum(g(ab, "operation", "")),
            enum(g(b, "logicOperation", "")), int(g(b, "writeMask", 0)),
        ])
    return {
        "alphaToCoverage": bool(g(bs, "alphaToCoverage", False)),
        "independentBlend": bool(g(bs, "independentBlend", False)),
        "blendFactor": [round(float(x), 4) for x in (g(bs, "blendFactor", []) or [])],
        "sampleMask": int(g(bs, "sampleMask", 0)),
        "blends": blends,
    }


def stencil_face(f) -> list:
    return [enum(g(f, "function", "")), enum(g(f, "failOperation", "")),
            enum(g(f, "depthFailOperation", "")), enum(g(f, "passOperation", "")),
            int(g(f, "reference", 0)), int(g(f, "compareMask", 0)), int(g(f, "writeMask", 0))]


def depth_state(om) -> dict:
    ds = g(om, "depthStencilState", None)
    if ds is None:
        return {}
    return {
        "depthEnable": bool(g(ds, "depthEnable", False)),
        "depthWrites": bool(g(ds, "depthWrites", False)),
        "depthFunction": enum(g(ds, "depthFunction", "")),
        "stencilEnable": bool(g(ds, "stencilEnable", False)),
        "front": stencil_face(g(ds, "frontFace", None)),
        "back": stencil_face(g(ds, "backFace", None)),
    }


def tex_filter(f) -> str:
    """TextureFilter is a struct (min/mag/mip + filter mode), not an enum."""
    if f is None:
        return "-"
    parts = [enum(g(f, n, "")) for n in ("minify", "magnify", "mip", "filter")]
    return "/".join(p for p in parts if p)


def sampler_entry(s) -> list:
    return [
        tex_filter(g(s, "filter", None)),
        enum(g(s, "addressU", "")), enum(g(s, "addressV", "")), enum(g(s, "addressW", "")),
        round(float(g(s, "mipBias", 0.0)), 4),
        int(g(s, "maxAnisotropy", 0)),
        enum(g(s, "compareFunction", "")),
        round(float(g(s, "minLOD", 0.0)), 4), round(float(g(s, "maxLOD", 0.0)), 4),
        border_color(s),
    ]


def border_color(s):
    """Border colour is a PixelValue union, not a plain array."""
    pv = g(s, "borderColorValue", None)
    if pv is None:
        return None
    for field in ("floatValue", "uintValue", "intValue"):
        vals = g(pv, field, None)
        if vals is None:
            continue
        try:
            return [round(float(x), 4) for x in vals]
        except Exception:
            continue
    return None


def descriptors(pipe, keys, cb_hashes: bool) -> dict:
    """Bound SRVs / samplers / constant buffers, keyed by (stage, type, index).

    Uses GetAllUsedDescriptors: the descriptors the bound shaders actually read.
    That is the right equality criterion — binding extra unread resources is not
    observable, failing to bind a read one is.
    """
    srvs, samps, cbs, uavs = [], [], [], []
    try:
        used = pipe.GetAllUsedDescriptors()
    except Exception:
        return {"srv": [], "sampler": [], "cb": [], "uav": []}

    for u in used:
        acc, desc, samp = g(u, "access", None), g(u, "descriptor", None), g(u, "sampler", None)
        if acc is None:
            continue
        stage = enum(g(acc, "stage", ""))
        idx = int(g(acc, "index", 0))
        arr = int(g(acc, "arrayElement", 0))
        dtype = enum(g(acc, "type", ""))
        slot = [stage, idx, arr]

        if dtype in ("Sampler",):
            samps.append(slot + sampler_entry(samp))
            continue

        res = g(desc, "resource", None)
        if dtype in ("ConstantBuffer",):
            off = int(g(desc, "byteOffset", 0))
            size = int(g(desc, "byteSize", 0))
            row = slot + [keys.buffer(res), off, size]
            if cb_hashes:
                row.append(keys.buffer_hash(res, off, min(size, 4096)))
            cbs.append(row)
            continue

        # Read-only or read-write resource view.
        row = slot + [
            keys.texture(res) if int(res or 0) in keys.textures else keys.buffer(res),
            fmt_str(g(desc, "format", None)),
            int(g(desc, "firstMip", 0)), int(g(desc, "numMips", 0)),
            int(g(desc, "firstSlice", 0)), int(g(desc, "numSlices", 0)),
            enum(g(desc, "textureType", "")),
        ]
        if dtype in ("ReadWriteImage", "ReadWriteBuffer", "ReadWriteTypedBuffer"):
            uavs.append(row)
        else:
            srvs.append(row)

    return {
        "srv": sorted(srvs), "sampler": sorted(samps),
        "cb": sorted(cbs), "uav": sorted(uavs),
    }


def output_merger(om, keys) -> dict:
    rts = []
    for i, d in enumerate(g(om, "renderTargets", []) or []):
        res = g(d, "resource", None)
        if is_null(res):
            continue
        rts.append([i, keys.texture(res), fmt_str(g(d, "format", None)),
                    int(g(d, "firstMip", 0)), int(g(d, "firstSlice", 0)),
                    int(g(d, "numSlices", 0))])
    dt = g(om, "depthTarget", None)
    depth = "-"
    if dt is not None and not is_null(g(dt, "resource", None)):
        depth = f"{keys.texture(g(dt, 'resource'))}|{fmt_str(g(dt, 'format', None))}"
    return {
        "rts": rts,
        "depth": depth,
        "depthReadOnly": bool(g(om, "depthReadOnly", False)),
        "stencilReadOnly": bool(g(om, "stencilReadOnly", False)),
    }


def record_draw(ctrl, action, keys, shader_cache, cb_hashes: bool) -> dict:
    st = ctrl.GetD3D11PipelineState()
    pipe = ctrl.GetPipelineState()
    ia = g(st, "inputAssembly", None)
    om = g(st, "outputMerger", None)
    rs = g(st, "rasterizer", None)

    ib = g(ia, "indexBuffer", None)
    rec = {
        "eid": int(action.eventId),
        "name": str(action.GetName(ctrl.GetStructuredFile())),
        "flags": enum(action.flags),
        "draw": [int(action.numIndices), int(action.numInstances),
                 int(action.indexOffset), int(action.vertexOffset),
                 int(action.instanceOffset), int(action.baseVertex)],
        "topology": enum(g(ia, "topology", "")),
        "layout": input_layout(ia),
        "ib": [keys.buffer(g(ib, "resourceId", None)),
               int(g(ib, "byteStride", 0)), int(g(ib, "byteOffset", 0))],
        "vb": vertex_buffers(ia, keys),
        "vs": shader_key(pipe, rd.ShaderStage.Vertex, shader_cache),
        "ps": shader_key(pipe, rd.ShaderStage.Pixel, shader_cache),
        "gs": shader_key(pipe, rd.ShaderStage.Geometry, shader_cache),
        "hs": shader_key(pipe, rd.ShaderStage.Hull, shader_cache),
        "ds": shader_key(pipe, rd.ShaderStage.Domain, shader_cache),
        "raster": rasterizer_state(rs),
        "viewports": viewports(rs),
        "scissors": scissors(rs),
        "blend": blend_state(om),
        "depthState": depth_state(om),
        "om": output_merger(om, keys),
    }
    rec.update(descriptors(pipe, keys, cb_hashes))
    return rec


# ── driver ───────────────────────────────────────────────────────────────────

def walk_actions(roots) -> list:
    out = []

    def rec(a):
        out.append(a)
        for c in a.children:
            rec(c)

    for a in roots:
        rec(a)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("capture")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--limit", type=int, default=0, help="stop after N draws (smoke test)")
    ap.add_argument("--no-cb-hashes", action="store_true",
                    help="skip constant-buffer content hashes (faster, weaker)")
    ap.add_argument("--include-clears", action="store_true",
                    help="also record Clear/Copy actions, not just draws")
    args = ap.parse_args()

    if not os.path.isfile(args.capture):
        print(f"no such capture: {args.capture}", file=sys.stderr)
        return 2

    rd.InitialiseReplay(rd.GlobalEnvironment(), [])
    cap = rd.OpenCaptureFile()
    if cap.OpenFile(args.capture, "", None) != rd.ResultCode.Succeeded:
        print("failed to open capture", file=sys.stderr)
        return 2
    if not cap.LocalReplaySupport():
        print("capture not replayable here", file=sys.stderr)
        return 2
    result, ctrl = cap.OpenCapture(rd.ReplayOptions(), None)
    if result != rd.ResultCode.Succeeded:
        print(f"failed to replay: {result}", file=sys.stderr)
        return 2

    actions = walk_actions(ctrl.GetRootActions())
    want = rd.ActionFlags.Drawcall
    if args.include_clears:
        want = want | rd.ActionFlags.Clear | rd.ActionFlags.Copy
    selected = [a for a in actions if int(a.flags) & int(want)]
    if args.limit:
        selected = selected[:args.limit]

    keys = ResourceKeys(ctrl)
    shader_cache: dict = {}

    header = {
        "_meta": True,
        "capture": os.path.basename(args.capture),
        "driver": str(cap.DriverName()),
        "totalActions": len(actions),
        "recorded": len(selected),
        "textures": len(ctrl.GetTextures()),
        "buffers": len(ctrl.GetBuffers()),
        "resources": len(ctrl.GetResources()),
    }

    n = 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(header) + "\n")
        for i, a in enumerate(selected):
            ctrl.SetFrameEvent(a.eventId, False)
            try:
                rec = record_draw(ctrl, a, keys, shader_cache, not args.no_cb_hashes)
            except Exception as e:  # one bad draw must not lose the run
                rec = {"eid": int(a.eventId), "error": f"{type(e).__name__}: {e}"}
            rec["idx"] = i
            fh.write(json.dumps(rec, sort_keys=True) + "\n")
            n += 1
            if n % 25 == 0:
                print(f"  {n}/{len(selected)}", file=sys.stderr, flush=True)

    print(f"{header['capture']}: {n} records -> {args.out}")
    print(f"  actions={header['totalActions']} textures={header['textures']} "
          f"buffers={header['buffers']} resources={header['resources']}")

    ctrl.Shutdown()
    cap.Shutdown()
    rd.ShutdownReplay()
    return 0


if __name__ == "__main__":
    sys.exit(main())
