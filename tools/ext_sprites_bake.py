#!/usr/bin/env python3
"""tools/ext_sprites_bake.py -- bake the Extensions sprites into the exe (NOT RETAIL; KITFREE.md §3).

usage: python tools/ext_sprites_bake.py            (rewrites src/ext/resources/ext_sprites_data.h)

Reads src/ext/ui/Dialog/ExtensionsSprites.rsc (our own sprite-sheet source: the sheet size,
_padForFiltering, _materialName, _imageName and the `_sprites` table of name -> source PNG) and
decodes every source PNG under src/ext/ui/Dialog/ with Python's zlib (no PIL) into straight RGBA8,
then writes the generated header the exe compiles in: one byte array per sprite and the table the
sheet builder (src/ext/resources/sheet_builder.h) packs at run time. The exe carries no PNG decoder.

Regenerate by hand after changing a PNG or the .rsc table and commit the header (it is our art,
drawn by tools/ext_sprites.py / tools/ext_icons/). The PNGs stay the source of truth.
"""
import os
import re
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RSC = os.path.join(ROOT, "src", "ext", "ui", "Dialog", "ExtensionsSprites.rsc")
RSC_DIR = os.path.dirname(RSC)
OUT = os.path.join(ROOT, "src", "ext", "resources", "ext_sprites_data.h")


def png_rgba(path):
    """Decode an 8-bit PNG (any colour type, no interlace) to (w, h, RGBA bytes)."""
    d = open(path, "rb").read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("ext_sprites_bake: %s is not a PNG" % path)
    o = 8
    idat = b""
    w = h = bd = ct = il = 0
    plte = None
    trns = None
    while o < len(d):
        ln, = struct.unpack_from(">I", d, o)
        typ = d[o + 4:o + 8]
        body = d[o + 8:o + 8 + ln]
        o += 12 + ln
        if typ == b"IHDR":
            w, h, bd, ct, _cm, _fm, il = struct.unpack_from(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
        elif typ == b"PLTE":
            plte = body
        elif typ == b"tRNS":
            trns = body
    if bd != 8 or il != 0:
        sys.exit("ext_sprites_bake: %s: only 8-bit non-interlaced PNGs (depth %d, interlace %d)"
                 % (path, bd, il))
    bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ct]
    stride = w * bpp
    raw = zlib.decompress(idat)
    out = bytearray()
    prev = bytearray(stride)
    p = 0
    for _y in range(h):
        f = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        prev = line
        for x in range(w):
            px = line[x * bpp:(x + 1) * bpp]
            if ct == 6:
                out += px
            elif ct == 2:
                out += px + b"\xff"
            elif ct == 0:
                out += bytes([px[0]] * 3) + b"\xff"
            elif ct == 4:
                out += bytes([px[0]] * 3) + bytes([px[1]])
            else:
                i = px[0]
                a = trns[i] if trns is not None and i < len(trns) else 255
                out += plte[i * 3:i * 3 + 3] + bytes([a])
    return w, h, bytes(out)


def read_rsc(path):
    text = open(path, encoding="latin-1").read()
    text = re.sub(r"//[^\n]*", "", text)

    def field(kind, name, conv):
        m = re.search(r"%s\s+%s\s*=\s*([^;]+);" % (kind, name), text)
        if m is None:
            sys.exit("ext_sprites_bake: %s has no `%s %s`" % (path, kind, name))
        return conv(m.group(1).strip())

    def unquote(s):
        return s.strip('"')

    sheet = {
        "materialName": field("String", "_materialName", unquote),
        "imageName": field("String", "_imageName", unquote),
        "width": field("int", "_imageWidth", int),
        "height": field("int", "_imageHeight", int),
        "pad": field("bool", "_padForFiltering", lambda s: s == "true"),
    }
    sprites = re.findall(r'\{\s*String\s+_name\s*=\s*"([^"]+)"\s*;\s*String\s+_source\s*=\s*"([^"]+)"\s*;\s*\}',
                         text)
    if not sprites:
        sys.exit("ext_sprites_bake: no `_sprites` entries in %s" % path)
    return sheet, sprites


def c_ident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def main():
    sheet, sprites = read_rsc(RSC)
    lines = []
    w = lines.append
    w("// src/ext/resources/ext_sprites_data.h -- GENERATED by tools/ext_sprites_bake.py; do not edit.")
    w("// NOT RETAIL (docs/extensions/KITFREE.md §3, block RSCSPRITE): the Extensions sprites of")
    w("// src/ext/ui/Dialog/ExtensionsSprites.rsc baked to straight RGBA8 (row-major, top-down), with")
    w("// the sheet parameters the .rsc names. Our own programmer art (tools/ext_sprites.py,")
    w("// tools/ext_icons/); the PNGs under src/ext/ui/Dialog/Sprite/Extensions/ are the source.")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("")
    w("#include \"ext/resources/sheet_builder.h\"")
    w("")
    w("namespace Ext {")
    w("namespace Resources {")
    w("namespace SpritesData {")
    w("")
    w("inline constexpr int  kSheetWidth      = %d;" % sheet["width"])
    w("inline constexpr int  kSheetHeight     = %d;" % sheet["height"])
    w("inline constexpr bool kPadForFiltering = %s;" % ("true" if sheet["pad"] else "false"))
    w("inline constexpr const char* kMaterialName = \"%s\";   // SpriteSheet::_materialName" % sheet["materialName"])
    w("inline constexpr const char* kImageName    = \"%s\";   // SpriteSheet::_imageName" % sheet["imageName"])
    w("")
    total = 0
    for name, source in sprites:
        png = os.path.join(RSC_DIR, source.replace("\\", "/"))
        pw, ph, rgba = png_rgba(png)
        total += len(rgba)
        w("// %s: %s, %d x %d" % (name, source, pw, ph))
        w("inline constexpr uint8_t kRgba_%s[%d] = {" % (c_ident(name), len(rgba)))
        for o in range(0, len(rgba), 32):
            w("    " + ",".join("%d" % b for b in rgba[o:o + 32]) + ",")
        w("};")
    w("")
    w("// The table the builder packs: name, group (the kit writes the source path, backslashes),")
    w("// size, pixels. Order = the .rsc's `_sprites` order = the sprite indices.")
    w("inline constexpr int kBitmapCount = %d;" % len(sprites))
    w("inline const SheetBitmap kBitmaps[kBitmapCount] = {")
    for name, source in sprites:
        png = os.path.join(RSC_DIR, source.replace("\\", "/"))
        pw, ph, _ = png_rgba(png)
        group = source.replace("/", "\\\\")
        w("    { \"%s\", \"%s\", %d, %d, kRgba_%s }," % (name, group, pw, ph, c_ident(name)))
    w("};")
    w("")
    w("}  // namespace SpritesData")
    w("}  // namespace Resources")
    w("}  // namespace Ext")
    w("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("ext_sprites_bake: %d sprites, %d RGBA bytes -> %s" % (len(sprites), total, os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
