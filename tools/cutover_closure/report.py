#!/usr/bin/env python3
"""Step 3 of the cutover closure: summarise closure.csv and emit the worklist.

    tools/ghidra_mcp/.venv/Scripts/python.exe tools/cutover_closure/report.py

Writes docs/runtime_port/closure/WORKLIST.md: every unported function in the
closure, CRT routines separated out (they are satisfied by our own C runtime,
not by porting), engine functions sorted smallest-first within namespace so a
session can take a run of leaves.  Prints the headline numbers.
"""
import collections
import csv
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "docs", "runtime_port", "closure")

# Names Ghidra gives to auto-identified C runtime code.  These do not need a
# port: reimpl-x64.exe links its own CRT.  If a name here turns out to be an
# engine function the fix is to rename it in Ghidra, not to edit this list.
CRT_RE = re.compile(r"^(_|__|FID_conflict:|`eh_|doexit|free$|malloc$|memcpy$|qsort$|shortsort$|strlen$|strtol$|strtoxl$|wcs|mbtowc$|wctomb|isleadbyte|write_(char|string|multi_char)$|IsProcessorFeaturePresent$)")


def main():
    rows = list(csv.DictReader(open(os.path.join(OUT, "closure.csv"))))
    unported = [r for r in rows if r["ported"] == "0"]
    crt = [r for r in unported if (r["namespace"].startswith("global_named") or r["namespace"] in ("_LocaleUpdate", "KERNEL32.DLL")) and CRT_RE.match(r["name"])]
    engine = [r for r in unported if r not in crt]
    total_b = sum(int(r["size"]) for r in rows)
    eng_b = sum(int(r["size"]) for r in engine)

    by_ns = collections.defaultdict(list)
    for r in engine:
        by_ns[r["namespace"]].append(r)

    lines = ["# Cutover worklist (generated by tools/cutover_closure/report.py)", ""]
    lines.append(f"Reachable functions in the DLL from our call surface: **{len(rows)}** ({total_b:,} bytes).")
    lines.append(f"Unported: **{len(unported)}**, of which **{len(crt)}** are C runtime routines our own CRT already provides.")
    lines.append(f"**Engine functions still to port: {len(engine)}** ({eng_b:,} bytes).")
    lines.append("")
    lines.append("This is a static lower bound (see CutoverClosure.java). Regenerate after every batch of ports; the number must only go down.")
    lines.append("")
    lines.append("| namespace | to port | bytes |")
    lines.append("|---|---:|---:|")
    for ns, rs in sorted(by_ns.items(), key=lambda kv: -sum(int(r["size"]) for r in kv[1])):
        lines.append(f"| {ns} | {len(rs)} | {sum(int(r['size']) for r in rs):,} |")
    lines.append("")
    for ns, rs in sorted(by_ns.items(), key=lambda kv: -sum(int(r["size"]) for r in kv[1])):
        lines.append(f"## {ns} ({len(rs)})")
        lines.append("")
        lines.append("| addr | name | bytes | exported |")
        lines.append("|---|---|---:|---|")
        for r in sorted(rs, key=lambda r: int(r["size"])):
            lines.append(f"| `{r['addr']}` | `{r['name']}` | {r['size']} | {'y' if r['external_export']=='1' else ''} |")
        lines.append("")
    lines.append("## C runtime routines in the closure (no port needed)")
    lines.append("")
    lines.append(", ".join(sorted(r["name"] for r in crt)))
    lines.append("")
    with open(os.path.join(OUT, "WORKLIST.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"reachable={len(rows)} unported={len(unported)} crt={len(crt)} ENGINE_TO_PORT={len(engine)} bytes={eng_b}")
    for ns, rs in sorted(by_ns.items(), key=lambda kv: -len(kv[1])):
        print(f"  {ns:14s} {len(rs):4d}  {sum(int(r['size']) for r in rs):7,d} B")
    print("wrote", os.path.join(OUT, "WORKLIST.md"))


if __name__ == "__main__":
    main()
