#!/usr/bin/env python3
"""tools/ext_rsc_embed.py -- embed our .rsc text sources into a generated C++ header.

usage: ext_rsc_embed.py <out.h> <file.rsc>...

Build step (CMakeLists.txt, target ext-rsc-text): each input under src/ext/ui/ becomes one
entry of Ext::RscText::kEmbedded, keyed by its path relative to src/ext/ui/ with forward
slashes ("Dialog/Extensions.rsc"). The exe carries only OUR text (NOT RETAIL; the kit's
resource/ files are never read here), and the resource provider (src/ext/resources/) builds
the objects from it at run time (docs/extensions/KITFREE.md, block RSCTEXT).
"""
import os
import sys


def c_literal(data):
    # One string literal per source line keeps the generated file readable and every
    # literal far below MSVC-style limits (GCC has none, but a diff reads better).
    out = []
    for line in data.split("\n"):
        s = line.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
        out.append('    "%s\\n"' % s)
    return "\n".join(out)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    out_path = sys.argv[1]
    entries = []
    for src in sys.argv[2:]:
        with open(src, "rb") as f:
            # LF only: a raw CR inside a C string literal ends the line for GCC's lexer.
            data = f.read().decode("utf-8").replace("\r\n", "\n").replace("\r", "")
        norm = src.replace("\\", "/")
        key = norm.split("/src/ext/ui/", 1)[1] if "/src/ext/ui/" in norm else os.path.basename(norm)
        entries.append((key, data))
    lines = []
    lines.append("// GENERATED by tools/ext_rsc_embed.py from src/ext/ui/ -- do not edit (CMake target ext-rsc-text).")
    lines.append("#pragma once")
    lines.append("namespace Ext { namespace RscText {")
    lines.append("struct EmbeddedFile { const char* path; const char* text; unsigned size; };")
    lines.append("static const EmbeddedFile kEmbedded[] = {")
    for key, data in entries:
        lines.append('  { "%s",' % key)
        lines.append(c_literal(data) + ",")
        lines.append("    %du }," % len(data.encode("utf-8")))
    lines.append("};")
    lines.append("static const int kEmbeddedCount = %d;" % len(entries))
    lines.append("} }  // namespace Ext::RscText")
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    # Write only on change: an unchanged header keeps every dependent object file up to date.
    try:
        with open(out_path, "r", encoding="utf-8", newline="") as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
