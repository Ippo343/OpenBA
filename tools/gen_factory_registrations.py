#!/usr/bin/env python3
# Codegen: standalone/factory_registrations.csv -> code/Game/Object/factory_registrations_bulk.cpp
#
# Re-extract the CSV by running the inline Ghidra script ExtractFactoryRegistrations
# (see notes/NOTES042526.md or run via mcp__ghidra-mcp__run_script_inline).
#
# Each row registers one exe-side BaseTypeInfo entry with NullFactory + NullInPlace.
# As real C++ reimplementations of each class land in code/Game/<Module>/<Class>.cpp,
# add the typeName to REIMPLEMENTED below — codegen will skip it, and the real
# REGISTER_TYPE in the per-class file takes over.
#
# Usage: python tools/gen_factory_registrations.py
import csv, os, sys

# Types whose real factory now lives in a per-class file under code/Game/.
# Codegen skips these so we don't double-register (which would CRC32-collide
# in Object::Factory::Startup's tree-insert).
REIMPLEMENTED = {
    "StatGoal",   # code/Game/Goal/statgoal.cpp
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV  = os.path.join(ROOT, "standalone", "factory_registrations.csv")
OUT  = os.path.join(ROOT, "code", "Game", "Object", "factory_registrations_bulk.cpp")

def parse_string_literal(s):
    # CSV stores a quoted string "Foo" as the field value '"Foo"', and the csv
    # reader unescapes to "Foo" with surrounding quotes intact in the cell.
    # Returns None for null sentinels like '(char *)0x0'.
    s = s.strip()
    if s in ("(char *)0x0", "0x0", "NULL", "(char*)0x0"):
        return None
    # Triple-quoted "Foo"
    if s.startswith('"""') and s.endswith('"""'):
        return s[3:-3]
    # Standard quoted "Foo"
    if s.startswith('"') and s.endswith('"'):
        return s[1:-1]
    return s

def main():
    if not os.path.exists(CSV):
        print(f"FATAL: {CSV} not found — re-extract via Ghidra first", file=sys.stderr)
        sys.exit(1)

    rows = []
    with open(CSV, encoding="utf-8") as f:
        for row in csv.reader(f):
            if not row or row[0].startswith("#"): continue
            rows.append(row)

    rows.sort(key=lambda r: r[0])  # by func address for stable output

    lines = []
    lines.append("// AUTO-GENERATED by tools/gen_factory_registrations.py")
    lines.append("// Source: standalone/factory_registrations.csv")
    lines.append("// DO NOT EDIT — regenerate from CSV.")
    lines.append("//")
    lines.append("// Bulk registration of all exe-side BaseTypeInfo entries that don't yet")
    lines.append("// have a real factory in code/Game/. Each entry uses NullFactory + NullInPlace")
    lines.append("// (placeholder).")
    lines.append("//")
    lines.append("// As real C++ reimplementations of each class land in")
    lines.append("//   code/Game/<Module>/<Class>.cpp")
    lines.append("// add the typeName to REIMPLEMENTED in tools/gen_factory_registrations.py")
    lines.append("// and re-run codegen. The per-class file's REGISTER_TYPE takes over.")
    lines.append("")
    lines.append("#ifdef STANDALONE_EXE")
    lines.append("#include \"factory_registration.h\"")
    lines.append("#include <cstdio>")
    lines.append("")
    lines.append("// Per-type tracing factories. When External::Load calls one of these,")
    lines.append("// we log which type was hit (so we know which real factory to write next)")
    lines.append("// before returning NULL. The NULL return triggers the IsDerivedFrom-NULL")
    lines.append("// crash at Runtime+0xC039A — but the trace tells us what to fix.")
    lines.append("namespace {")
    lines.append("    void* NullInPlace(void* /*mem*/) { return nullptr; }")
    lines.append("")
    lines.append("    // Generic stub that logs the name. Each REGISTER_TYPE entry below")
    lines.append("    // points at a unique trampoline that calls this with its typeName.")
    lines.append("    void* LogAndReturnNull(const char* typeName) {")
    lines.append("        std::fprintf(stderr, \"[NullFactory] Hit for type: %s\\n\", typeName);")
    lines.append("        std::fflush(stderr);")
    lines.append("        return nullptr;")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("// Macro: declares a per-type factory + registers it in one line.")
    lines.append("#define REGISTER_NULL_FACTORY(Name, Parent)                                  \\")
    lines.append("    namespace { void* NullFactory_##Name() { return LogAndReturnNull(#Name); } } \\")
    lines.append("    REGISTER_TYPE(Name, Parent, &NullFactory_##Name, &NullInPlace)")
    lines.append("#define REGISTER_NULL_FACTORY_FULL(Name, Parent, Abstract)                   \\")
    lines.append("    namespace { void* NullFactory_##Name() { return LogAndReturnNull(#Name); } } \\")
    lines.append("    REGISTER_TYPE_FULL(Name, Parent, Abstract, &NullFactory_##Name, &NullInPlace)")
    lines.append("")

    abstract_count = 0
    skipped = []
    for r in rows:
        addr, fname, storage, name, parent, abstract, factory, inplace = r
        type_name = parse_string_literal(name)
        parent_s  = parse_string_literal(parent)
        abstract_s = parse_string_literal(abstract)

        if not type_name:
            print(f"WARN: row {addr} ({fname}) has no name; skipping", file=sys.stderr)
            continue
        if not type_name.replace("_","").isalnum():
            print(f"WARN: row {addr} name {type_name!r} is not a valid C identifier", file=sys.stderr)

        if type_name in REIMPLEMENTED:
            skipped.append(type_name)
            continue

        parent_arg = f'"{parent_s}"' if parent_s else "nullptr"

        comment = f"// {addr} {fname}"
        if abstract_s:
            abstract_arg = f'"{abstract_s}"'
            lines.append(f"REGISTER_NULL_FACTORY_FULL({type_name}, {parent_arg}, {abstract_arg});  {comment}")
            abstract_count += 1
        else:
            lines.append(f"REGISTER_NULL_FACTORY({type_name}, {parent_arg});  {comment}")

    lines.append("")
    lines.append("#endif  // STANDALONE_EXE")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"Wrote {OUT}")
    print(f"  Entries: {len(rows) - len(skipped)} (with abstract: {abstract_count})")
    if skipped:
        print(f"  Skipped (reimplemented): {', '.join(skipped)}")

if __name__ == "__main__":
    main()
