#!/usr/bin/env python3
"""Extract the MSVC CRT math coefficient tables out of Runtime-x64.dll.

Emits runtime/src/crt/msvc_libm_tables.h as RAW BIT PATTERNS (uint64_t / uint32_t),
never as retyped decimal literals: a decimal round-trip is exactly the kind of
last-bit error this port exists to remove.

Usage: python tools/extract_crt_tables.py [path-to-Runtime-x64.dll] > runtime/src/crt/msvc_libm_tables.h
"""
import struct, sys, os

DLL = sys.argv[1] if len(sys.argv) > 1 else r"C:\GOG Games\Banished\Runtime-x64.dll"
IMAGE_BASE = 0x180000000

def load_sections(path):
    data = open(path, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    assert data[pe:pe+4] == b'PE\0\0'
    nsec = struct.unpack_from('<H', data, pe+6)[0]
    optsz = struct.unpack_from('<H', data, pe+20)[0]
    secs = []
    off = pe + 24 + optsz
    for i in range(nsec):
        name = data[off:off+8].rstrip(b'\0').decode()
        vsize, vaddr, rawsize, rawptr = struct.unpack_from('<IIII', data, off+8)
        secs.append((name, vaddr, vsize, rawptr, rawsize))
        off += 40
    return data, secs

DATA, SECS = load_sections(DLL)

def read(va, n):
    rva = va - IMAGE_BASE
    for name, vaddr, vsize, rawptr, rawsize in SECS:
        if vaddr <= rva < vaddr + max(vsize, rawsize):
            off = rawptr + (rva - vaddr)
            return DATA[off:off+n]
    raise KeyError(hex(va))

def u64s(va, count):
    b = read(va, count*8)
    return list(struct.unpack_from('<%dQ' % count, b, 0))
def u32s(va, count):
    b = read(va, count*4)
    return list(struct.unpack_from('<%dI' % count, b, 0))

def emit_u64(name, va, count, per_line=2, comment=None):
    vals = u64s(va, count)
    print("// %s  @ %#x  (%d entries)" % (comment or name, va, count))
    print("alignas(16) static const uint64_t %s[%d] = {" % (name, count))
    for i in range(0, count, per_line):
        chunk = vals[i:i+per_line]
        line = "    " + ", ".join("0x%016xull" % v for v in chunk) + ","
        line += "  // [%d] %s" % (i, ", ".join(repr(struct.unpack('<d', struct.pack('<Q', v))[0]) for v in chunk))
        print(line)
    print("};")
    print()

def emit_u32(name, va, count, per_line=4, comment=None):
    vals = u32s(va, count)
    print("// %s  @ %#x  (%d entries)" % (comment or name, va, count))
    print("static const uint32_t %s[%d] = {" % (name, count))
    for i in range(0, count, per_line):
        chunk = vals[i:i+per_line]
        print("    " + ", ".join("0x%08xu" % v for v in chunk) + ",")
    print("};")
    print()

def scalar(name, va, comment=""):
    v = u64s(va, 1)[0]
    f = struct.unpack('<d', struct.pack('<Q', v))[0]
    print("static const uint64_t %-14s = 0x%016xull;  // %#x = %r %s" % (name, v, va, f, comment))

